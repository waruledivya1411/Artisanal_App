/// The language chosen on the picker. Screens read this when they draw text.
class AppLang {
  static String current = 'en-US';

  static String get code {
    final value = current.toLowerCase();
    if (value.startsWith('as')) return 'as';
    if (value.startsWith('or')) return 'or';
    if (value.startsWith('te')) return 'te';
    return 'en';
  }
}

/// English [text] in the language the artisan picked.
String tr(String text) {
  if (AppLang.code == 'en' || text.isEmpty) return text;
  final table = AppLang.code == 'as'
      ? _as
      : AppLang.code == 'or'
      ? _or
      : _te;
  final direct = table[text];
  if (direct != null) return direct;
  return _templated(text, table) ?? text;
}

String? _templated(String text, Map<String, String> table) {
  String? fill(String key, Map<String, String> vars) {
    final pattern = table[key];
    if (pattern == null) return null;
    var out = pattern;
    vars.forEach((name, value) {
      out = out.replaceAll('{$name}', tr(value));
    });
    return out;
  }

  final tasks = RegExp(r'^(\d+) OF (\d+) TASKS DONE$').firstMatch(text);
  if (tasks != null) {
    return fill('{done} OF {total} TASKS DONE', {
      'done': tasks.group(1)!,
      'total': tasks.group(2)!,
    });
  }
  final move = RegExp(r'^Move the (.+) into the frame$').firstMatch(text);
  if (move != null) {
    return fill('Move the {product} into the frame', {
      'product': move.group(1)!,
    });
  }
  final fit = RegExp(r'^Fit the (.+) inside the dotted line$').firstMatch(text);
  if (fit != null) {
    return fill('Fit the {product} inside the dotted line', {
      'product': fit.group(1)!,
    });
  }
  final nextTask = RegExp(r'^Next task: (.+)$').firstMatch(text);
  if (nextTask != null) {
    return fill('Next task: {task}', {'task': nextTask.group(1)!});
  }
  final nextPart = RegExp(r'^Next part · (.+)$').firstMatch(text);
  if (nextPart != null) {
    return fill('Next part · {part}', {'part': nextPart.group(1)!});
  }
  final finish = RegExp(r'^Finish (.+) first$').firstMatch(text);
  if (finish != null) {
    return fill('Finish {part} first', {'part': finish.group(1)!});
  }
  final step = RegExp(r'^Step (\d+)$').firstMatch(text);
  if (step != null) {
    return fill('Step {n}', {'n': step.group(1)!});
  }
  final taskOf = RegExp(r'^TASK (\d+) · (\d+) OF (\d+)$').firstMatch(text);
  if (taskOf != null) {
    return fill('TASK {task} · {step} OF {total}', {
      'task': taskOf.group(1)!,
      'step': taskOf.group(2)!,
      'total': taskOf.group(3)!,
    });
  }
  final setup = RegExp(
    r'^Set up your page\. Step (\d+) of (\d+)\.$',
  ).firstMatch(text);
  if (setup != null) {
    return fill('Set up your page. Step {n} of {total}.', {
      'n': setup.group(1)!,
      'total': setup.group(2)!,
    });
  }
  final plus = RegExp(r'^\+ (.+)$').firstMatch(text);
  if (plus != null) {
    return fill('+ {label}', {'label': plus.group(1)!});
  }
  final named = RegExp(r'^Name @(.+)$').firstMatch(text);
  if (named != null) {
    final pattern = table['Name @{handle}'];
    if (pattern == null) return null;
    return pattern.replaceAll('{handle}', named.group(1)!);
  }
  return null;
}

/// Body text in a font that can draw the chosen script.
TextStyle appType({
  Color? color,
  double? fontSize,
  FontWeight? fontWeight,
  double? height,
  double? letterSpacing,
  FontStyle? fontStyle,
}) {
  final spacing = AppLang.code == 'en' ? letterSpacing : 0.0;
  switch (AppLang.code) {
    case 'as':
      return GoogleFonts.notoSansBengali(
        color: color,
        fontSize: fontSize,
        fontWeight: fontWeight,
        height: height,
        letterSpacing: spacing,
        fontStyle: fontStyle,
      );
    case 'or':
      return GoogleFonts.notoSansOriya(
        color: color,
        fontSize: fontSize,
        fontWeight: fontWeight,
        height: height,
        letterSpacing: spacing,
        fontStyle: fontStyle,
      );
    case 'te':
      return GoogleFonts.notoSansTelugu(
        color: color,
        fontSize: fontSize,
        fontWeight: fontWeight,
        height: height,
        letterSpacing: spacing,
        fontStyle: fontStyle,
      );
    default:
      return GoogleFonts.plusJakartaSans(
        color: color,
        fontSize: fontSize,
        fontWeight: fontWeight,
        height: height,
        letterSpacing: spacing,
        fontStyle: fontStyle,
      );
  }
}

